/**
 * 5. Pushes the generated bot to the user's GitHub repository using their PAT
 */
async function pushBotToGitHub(workspacePath, repoUrl, pat, botName) {
    let cleanUrl = repoUrl.trim().replace(/\.git$/, '');
    const ghMatch = cleanUrl.match(/github\.com[\/:]([^\/]+)\/([^\/]+)/i);
    if (!ghMatch) {
        throw new Error('Invalid GitHub repository URL. Format must be: https://github.com/username/repository');
    }

    const [, owner, repo] = ghMatch;
    const cleanPat = pat.trim();
    const authRemoteUrl = `https://${cleanPat}@github.com/${owner}/${repo}.git`;
    const safePublicUrl = `https://github.com/${owner}/${repo}`;

    const exec = child_process.execSync;

    // Initialize git
    exec('git init', { cwd: workspacePath, stdio: 'pipe' });
    exec('git config user.name "StarryBotStudio"', { cwd: workspacePath, stdio: 'pipe' });
    exec('git config user.email "botstudio@starry.ai"', { cwd: workspacePath, stdio: 'pipe' });
    exec('git branch -M main', { cwd: workspacePath, stdio: 'pipe' });
    exec('git add .', { cwd: workspacePath, stdio: 'pipe' });
    exec(`git commit -m "feat: initial bot architecture scaffolded by Starry Bot Studio"`, { cwd: workspacePath, stdio: 'pipe' });

    // Push to remote using PAT
    exec(`git remote add origin ${authRemoteUrl}`, { cwd: workspacePath, stdio: 'pipe' });
    exec(`git push -u origin main --force`, { cwd: workspacePath, stdio: 'pipe' });

    // Sanitize remote URL immediately so PAT is never kept on disk
    try {
        exec(`git remote set-url origin ${safePublicUrl}`, { cwd: workspacePath, stdio: 'pipe' });
    } catch (e) {}

    return {
        repoUrl: safePublicUrl,
        owner,
        repo
    };
}

/**
 * 6. Packages the generated bot into a downloadable .zip archive
 */
async function packageBotZip(workspacePath, botSlug) {
    const zipFilename = `${botSlug}.zip`;
    const zipPath = path.join(BOTS_ROOT_DIR, zipFilename);
    if (fs.existsSync(zipPath)) {
        try { fs.unlinkSync(zipPath); } catch (e) {}
    }

    child_process.execSync(`zip -r "${zipPath}" . -x "*.git*"`, { cwd: workspacePath, stdio: 'pipe' });
    return {
        zipPath,
        zipFilename
    };
}

/**
 * Helper to extract a friendly bot name from a user prompt
 */
function extractBotName(prompt) {
    if (!prompt) return 'custom-bot';
    const match = prompt.match(/(?:named|called|name is)\s+([a-zA-Z0-9_-]+)/i);
    if (match && match[1]) return match[1];

    if (/music/i.test(prompt)) return 'starlight-music-bot';
    if (/mod(?:eration)?/i.test(prompt)) return 'aegis-mod-bot';
    if (/economy/i.test(prompt)) return 'celestial-economy-bot';
    return 'starry-autonomous-bot';
}

