/**
 * 1. Intent Detection: Checks if a prompt asks to code or build a Discord bot
 */
function isBotCreationRequest(prompt) {
    if (!prompt || typeof prompt !== 'string') return false;
    const str = prompt.toLowerCase().trim();

    // Direct command triggers
    if (/^[,/](?:codebot|buildbot|makebot|botstudio|generatebot)\b/i.test(str)) {
        return true;
    }

    const hasBot = /\b(?:discord\s+bot|discord\.js\s+bot|music\s+bot|mod(?:eration)?\s+bot|economy\s+bot|ticket\s+bot|complex\s+bot|custom\s+bot|a\s+bot|my\s+bot)\b/i.test(str) ||
                   /\b(?:bot\s+for\s+me|bot\s+from\s+scratch)\b/i.test(str);

    const hasAction = /\b(?:code|build|make|create|develop|program|scaffold|generate|write)\b/i.test(str);

    if (hasAction && hasBot) {
        return true;
    }

    return false;
}

/**
 * 2. Creates a new Bot Studio interactive session
 */
function createBotStudioSession(userId, prompt, guildId = null) {
    const sessionId = Math.random().toString(36).substring(2, 10);
    const sessionData = {
        id: sessionId,
        userId,
        guildId,
        prompt: prompt.trim(),
        cleanPrompt: prompt.replace(/--(?:dev|code|coder|flash|pro)\b/gi, '').trim(),
        createdAt: Date.now()
    };
    botStudioSessions.set(sessionId, sessionData);

    // Auto-expire session after 30 minutes
    setTimeout(() => botStudioSessions.delete(sessionId), 30 * 60 * 1000);
    return sessionData;
}

